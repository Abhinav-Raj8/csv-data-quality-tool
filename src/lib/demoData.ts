// ─── Injection rates ──────────────────────────────────────────────────────────
// Tuned so that roughly 80-90% of rows come out fully clean after validation
// (see src/lib/validation.ts). These are independent per-row probabilities,
// not a hardcoded pass/fail outcome — the actual quality score still comes
// entirely from running the validator against whatever gets generated.

const RATES = {
  duplicateOrderId:   0.015,  // reuse an already-assigned Order_ID
  emailMissing:       0.015,
  emailInvalid:       0.010,
  phoneMissing:       0.015,
  phoneInvalid:       0.010,
  dateNonIso:         0.040,  // recognizable but non-ISO format (warning)
  productWhitespace:  0.010,
  nameDistortion:     0.018,  // case/whitespace distortions
  paymentIdMissing:   0.015,
  paymentStatusBad:   0.015,
  paymentMismatch:    0.12,   // reconciliation-only, doesn't affect quality score
};

export const TOTAL_RECORDS = 2000;
const EXACT_DUPLICATE_ROWS = 20; // ~1% — copies live inside the 2000, not appended after

// Bumped whenever the generation logic changes in a way that affects row
// count or content. Compared against a value cached in localStorage on
